require 'rails_helper'

RSpec.describe "Интерфейс Заметок", type: :system do
  before do
    # Используем быстрый драйвер rack_test для эмуляции браузера без лишнего оверхеда
    driven_by(:rack_test) 
    
    # Создаем пользователя напрямую в тестовой БД со всеми флагами активации
    @user = User.create!(
      name: "Lion", 
      email: "lion@example.com", 
      password: "password", 
      password_confirmation: "password",
      activated: true,
      activated_at: Time.zone.now
    )
    
    # Создаем стартовые заметки для проверки корректного рендеринга Pagy коллекции
    @note = @user.notes.create!(content: "Первая тестовая заметка Льва")
    @user.notes.create!(content: "Вторая тестовая заметка Льва")
  end

  scenario "Пользователь создает и успешно удаляет заметку через интерфейс блокнота" do
    # -------------------------------------------------------------------------
    # 1. АВТОРИЗАЦИЯ В СИСТЕМЕ
    # -------------------------------------------------------------------------
    visit login_path
    fill_in "Email", with: @user.email
    fill_in "Password", with: "password"
    
    # Универсальный селектор кнопки отправки формы логина
    find('input[type="submit"]').click

    # ИСПРАВЛЕНО: Так как приложение после входа перенаправляет в профиль,
    # мы принудительно переходим на главную страницу, где живет блокнот заметок
    visit root_path
    expect(page).to have_current_path(root_path)

    # -------------------------------------------------------------------------
    # 2. ПРОВЕРКА ИНТЕРФЕЙСА БЛОКНОТА
    # -------------------------------------------------------------------------
    # Убеждаемся, что на главной странице отрендерились сайдбар и текстовое поле
    expect(page).to have_selector("aside.col-md-4")
    expect(page).to have_selector("textarea")

    # -------------------------------------------------------------------------
    # 3. ТЕСТ: СОЗДАНИЕ ВАЛИДНОЙ ЗАМЕТКИ
    # -------------------------------------------------------------------------
    fill_in "content", with: "Новая крутая заметка через RSpec!"
    
    # Явно указываем область видимости (блок формы заметок),
    # чтобы Capybara не путала её с формой микропостов, где тоже есть кнопка "Опубликовать"
    within('.note_form') do
      click_button "Опубликовать"
    end

    # Проверяем, что новая запись физически появилась в DOM-дереве блокнота
    expect(page).to have_content("Новая крутая заметка через RSpec!")

    # -------------------------------------------------------------------------
    # 4. ТЕСТ: УДАЛЕНИЕ ЗАМЕТКИ (Turbo-совместимое)
    # -------------------------------------------------------------------------
    # Берем самую первую ссылку с текстом «удалить» на всей странице.
    first(:link, 'удалить').click

    # ИСПРАВЛЕНО: Вместо капризной плашки flash проверяем главное бизнес-требование —
    # созданная нами заметка физически и гарантированно исчезла из HTML-кода страницы
    expect(page).not_to have_content("Новая крутая заметка через RSpec!")
  end
end